/* Who's struggling? Scrollytelling story built with D3 v7.
   Data: window.STORY_DATA (viz/data.js, generated by src/build_viz_data.py).
   Each section has a sticky figure and text steps; when a step reaches the
   trigger line, its section's update(step) redraws the figure. */

(function () {
  "use strict";

  // ================================================================ settings

  const DATA = window.STORY_DATA;

  // SVG coordinates equal screen pixels: each chart is as wide as its container.
  const SIZE = {
    maxWidth: 640,
    minWidth: 300,
    narrowAxis: 500,
    narrowGrids: 560,
    hitTarget: 24,
    marker: 6,
    labelGap: 10,
    rowLabelGap: 12,
    wrapGap: 16,
    dodge: 12,
  };

  const UNITS = {
    perGrid: 100,
    perRow: 10,
    cell: 13,
    cellNarrow: 10,
    dotRadius: 0.36, // share of the cell
    gridGap: 30,
    top: 36,
    labelAbove: 14,
    labelBelow: 22,
    blockExtra: 82,
    hitPadding: 6,
  };

  const DOT_RANGE = {
    rowHeight: 54,
    labelWidth: 190,
    labelShare: 0.38,
    marginTop: 10,
    marginRight: 70,
    marginRightNarrow: 52,
    marginBottom: 36,
    titleOffset: 4,
    ticks: 6,
    ticksNarrow: 4,
    screenShare: 0.4, // on phones, a fitScreen chart's rows use at most this share of the screen height
    minRowHeight: 14,
  };

  const WATERFALL = {
    rowHeight: 34,
    barHeight: 20,
    radius: 3,
    labelWidth: 200,
    labelGap: 8,
  };

  const FOREST = {
    rowHeight: 20,
    rowHeightNarrow: 24,
    labelWidth: 210,
    ticks: [0.5, 0.75, 1, 1.5, 2, 3],
    domain: [0.5, 3.2],
  };

  const OPACITY = { focus: 1, context: 0.45, faded: 0.2, hidden: 0 };

  const COLOR = {
    accent: "var(--accent)",
    series: "var(--series-1)",
    muted: "var(--muted)",
    neutral: "var(--neutral-dot)",
    total: "var(--ink-2)",
  };

  const EMPLOYMENT = ["Full-time", "Part-time", "Looking for work", "Not looking for work"];
  const BANDS = ["0-5", "6-11", "12-17"];
  const BAND_TEXT = { "0-5": "under 6", "6-11": "6 to 11", "12-17": "12 to 17" };

  // ================================================================ helpers

  const {
    MOTION, fmt1, fmtInt, signed, ciRange, ciText, byId, isMobile, onResize,
    attachTooltip, legend, table, COLUMN, onSteps, initThemeToggle,
  } = window.Viz;

  function childLabel(band) {
    return `Child ${BAND_TEXT[band] || band}`;
  }

  function chartWidth(elementId) {
    const width = byId(elementId).clientWidth || SIZE.maxWidth;
    return Math.max(SIZE.minWidth, Math.min(SIZE.maxWidth, width));
  }

  // Remembers the last state so the chart can redraw itself after a resize.
  function redrawable(svg, draw) {
    let last = null;
    onResize(() => {
      if (last && svg.style("display") !== "none") {
        draw(last);
      }
    });
    return (state) => {
      last = state;
      draw(state);
    };
  }

  function wrapLabel(selection, maxWidth) {
    selection.each(function () {
      const text = d3.select(this);
      const words = text.text().split(/\s+/);
      const x = text.attr("x");
      text.text(null).attr("dy", null);
      let line = [];
      let tspan = text.append("tspan").attr("x", x);
      let lines = 1;
      for (const word of words) {
        line.push(word);
        tspan.text(line.join(" "));
        if (tspan.node().getComputedTextLength() > maxWidth && line.length > 1) {
          line.pop();
          tspan.text(line.join(" "));
          line = [word];
          tspan = text.append("tspan").attr("x", x).attr("dy", "1.2em").text(word);
          lines += 1;
        }
      }
      text.select("tspan").attr("dy", `${0.35 - (lines - 1) * 0.6}em`);
    });
  }

  // ================================================================ charts

  /* Up to four 10 x 10 grids. Each group: {key, label, pct, detail};
     the first round(pct) dots are highlighted. */
  function unitGrids(elementId) {
    const svg = d3.select(`#${elementId}`).append("svg");

    function draw(groups) {
      const width = chartWidth(elementId);
      const narrow = width < SIZE.narrowGrids;
      const cell = narrow ? UNITS.cellNarrow : UNITS.cell;
      const gridSize = cell * UNITS.perRow;
      const blockHeight = gridSize + UNITS.blockExtra;
      const columns = narrow ? Math.min(2, groups.length) : groups.length;
      svg.attr("viewBox", `0 0 ${width} ${Math.ceil(groups.length / columns) * blockHeight}`);
      const left = (width - (columns * gridSize + (columns - 1) * UNITS.gridGap)) / 2;
      const position = (d, i) => {
        const x = left + (i % columns) * (gridSize + UNITS.gridGap);
        const y = UNITS.top + Math.floor(i / columns) * blockHeight;
        return `translate(${x},${y})`;
      };

      const grids = svg.selectAll("g.grid").data(groups, (d) => d.key);
      grids.exit().transition().duration(MOTION.exit).style("opacity", OPACITY.hidden).remove();

      const entered = grids.enter().append("g")
        .attr("class", "grid")
        .style("opacity", OPACITY.hidden)
        .attr("transform", position);
      entered.append("text").attr("class", "group-label").attr("text-anchor", "middle");
      entered.selectAll("circle.dot").data(d3.range(UNITS.perGrid)).enter().append("circle").attr("class", "dot");
      entered.append("text").attr("class", "value-label").attr("text-anchor", "middle");
      entered.append("rect").attr("class", "hit");

      const merged = entered.merge(grids);
      merged.transition().duration(MOTION.duration).style("opacity", OPACITY.focus).attr("transform", position);
      merged.select("text.group-label").attr("x", gridSize / 2).attr("y", -UNITS.labelAbove).text((d) => d.label);
      merged.select("text.value-label").attr("x", gridSize / 2).attr("y", gridSize + UNITS.labelBelow)
        .text((d) => `${Math.round(d.pct)} in ${UNITS.perGrid}`);
      merged.select("rect.hit")
        .attr("x", -UNITS.hitPadding).attr("y", -UNITS.hitPadding)
        .attr("width", gridSize + 2 * UNITS.hitPadding).attr("height", gridSize + 2 * UNITS.hitPadding);
      merged.each(function (group) {
        const on = Math.round(group.pct);
        d3.select(this).selectAll("circle.dot")
          .attr("r", cell * UNITS.dotRadius)
          .attr("cx", (i) => (i % UNITS.perRow) * cell + cell / 2)
          .attr("cy", (i) => Math.floor(i / UNITS.perRow) * cell + cell / 2)
          .classed("on", (i) => i < on);
      });
      attachTooltip(merged.select("rect.hit"), (d) => `${fmt1(d.pct)}%`, (d) => `${d.label}. ${d.detail}`);
    }

    return { update: redrawable(svg, draw) };
  }

  /* Rows on the y axis; several series per row are dodged vertically, unless
     state.connect draws them on one line joined by a connector.
     points: [{row, series, value, ci, color, opacity, label, tooltip}] */
  function dotRange(elementId, options = {}) {
    const svg = d3.select(`#${elementId}`).append("svg");
    const plot = svg.append("g");
    const xAxis = svg.append("g").attr("class", "x-axis");
    const zero = svg.append("line").attr("class", "zero-line");
    const xTitle = svg.append("text").attr("class", "axis-text").attr("text-anchor", "middle");

    function draw(state) {
      const width = chartWidth(elementId);
      const narrow = width < SIZE.narrowAxis;
      let rowHeight = (narrow && options.rowHeightNarrow) || options.rowHeight || DOT_RANGE.rowHeight;
      if (options.fitScreen && isMobile()) {
        const room = window.innerHeight * DOT_RANGE.screenShare - DOT_RANGE.marginTop - DOT_RANGE.marginBottom;
        rowHeight = Math.max(DOT_RANGE.minRowHeight, Math.min(rowHeight, room / state.rows.length));
      }
      const margin = {
        top: DOT_RANGE.marginTop,
        right: narrow ? DOT_RANGE.marginRightNarrow : DOT_RANGE.marginRight,
        bottom: DOT_RANGE.marginBottom,
        left: Math.min(options.labelWidth || DOT_RANGE.labelWidth, Math.round(width * DOT_RANGE.labelShare)),
      };
      const rows = state.rows;
      const plotBottom = margin.top + rows.length * rowHeight;
      const height = plotBottom + margin.bottom;
      svg.attr("viewBox", `0 0 ${width} ${height}`);

      const x = (state.log ? d3.scaleLog() : d3.scaleLinear()).domain(state.domain).range([margin.left, width - margin.right]);
      const y = d3.scaleBand().domain(rows.map((r) => r.key)).range([margin.top, plotBottom]);
      const rowMiddle = (row) => y(row) + y.bandwidth() / 2;
      const seriesKeys = state.seriesOrder || [...new Set(state.points.map((p) => p.series))];
      const dodge = d3.scaleBand().domain(seriesKeys).range([-SIZE.dodge, SIZE.dodge]).padding(0.2);
      const dodged = seriesKeys.length > 1 && !state.connect;
      const yOf = (p) => rowMiddle(p.row) + (dodged ? dodge(p.series) + dodge.bandwidth() / 2 : 0);
      const showCi = (p) => Boolean(p.ci) && !state.connect;
      const low = (p) => x(showCi(p) ? p.ci[0] : p.value);
      const high = (p) => x(showCi(p) ? p.ci[1] : p.value);

      xAxis.attr("transform", `translate(0,${plotBottom})`)
        .transition().duration(MOTION.duration)
        .call(d3.axisBottom(x)
          .tickValues(state.tickValues || null)
          .ticks(narrow ? DOT_RANGE.ticksNarrow : DOT_RANGE.ticks)
          .tickSize(-(rows.length * rowHeight))
          .tickFormat(state.tickFormat || ((v) => v)));
      xAxis.selectAll(".tick line").attr("class", "gridline");
      xTitle.attr("x", (margin.left + width - margin.right) / 2).attr("y", height - DOT_RANGE.titleOffset)
        .text((narrow && state.xTitleShort) || state.xTitle || "");

      // Reference line: 0 for differences, 1 for odds ratios.
      const reference = state.reference ?? 0;
      const inside = state.domain[0] < reference && state.domain[1] > reference;
      zero.transition().duration(MOTION.duration)
        .attr("x1", x(reference)).attr("x2", x(reference)).attr("y1", margin.top).attr("y2", plotBottom)
        .style("opacity", inside ? OPACITY.focus : OPACITY.hidden);

      const labels = plot.selectAll("text.row-label").data(rows, (r) => r.key);
      labels.exit().remove();
      labels.enter().append("text").attr("class", "row-label").attr("text-anchor", "end")
        .merge(labels)
        .attr("x", margin.left - SIZE.rowLabelGap)
        .attr("y", (r) => rowMiddle(r.key))
        .classed("is-bold", (r) => Boolean(r.bold))
        .text((r) => (narrow && r.labelNarrow) || r.label)
        .call(wrapLabel, margin.left - SIZE.wrapGap);

      const pairs = state.connect ? d3.groups(state.points, (p) => p.row) : [];
      const connectors = plot.selectAll("line.connector").data(pairs, ([row]) => row);
      connectors.exit().remove();
      connectors.enter().append("line").attr("class", "connector").merge(connectors)
        .transition().duration(MOTION.duration)
        .attr("x1", ([, pts]) => x(d3.min(pts, (p) => p.value)))
        .attr("x2", ([, pts]) => x(d3.max(pts, (p) => p.value)))
        .attr("y1", ([row]) => rowMiddle(row))
        .attr("y2", ([row]) => rowMiddle(row))
        .style("opacity", ([, pts]) => d3.min(pts, (p) => p.opacity));

      const marks = plot.selectAll("g.mark").data(state.points, (p) => `${p.row}|${p.series}`);
      marks.exit().transition().duration(MOTION.exit).style("opacity", OPACITY.hidden).remove();
      const entered = marks.enter().append("g").attr("class", "mark")
        .style("opacity", OPACITY.hidden)
        .attr("transform", (p) => `translate(0,${yOf(p)})`);
      entered.append("line").attr("class", "ci");
      entered.append("circle").attr("class", "marker").attr("r", SIZE.marker);
      entered.append("text").attr("class", "value-label").attr("dy", "0.35em");
      entered.append("rect").attr("class", "hit").attr("height", SIZE.hitTarget).attr("y", -SIZE.hitTarget / 2);

      const merged = entered.merge(marks);
      merged.transition().duration(MOTION.duration)
        .style("opacity", (p) => p.opacity)
        .attr("transform", (p) => `translate(0,${yOf(p)})`);
      merged.select("line.ci")
        .attr("stroke", (p) => p.color)
        .style("display", (p) => (showCi(p) ? null : "none"))
        .transition().duration(MOTION.duration)
        .attr("x1", low)
        .attr("x2", high);
      merged.select("circle.marker")
        .attr("fill", (p) => p.color)
        .transition().duration(MOTION.duration)
        .attr("cx", (p) => x(p.value));
      merged.select("text.value-label")
        .text((p) => p.label || "")
        .transition().duration(MOTION.duration)
        .attr("x", (p) => high(p) + SIZE.labelGap);
      merged.select("rect.hit")
        .attr("x", (p) => low(p) - SIZE.hitTarget / 2)
        .attr("width", (p) => high(p) - low(p) + SIZE.hitTarget);
      attachTooltip(merged.select("rect.hit"),
        (p) => `${state.signed ? signed(p.value) : fmt1(p.value)}${state.unit || ""}`,
        (p) => `${p.tooltip || p.series} · ${ciText(p.ci)}`);
      // Hidden marks can't be focused or hovered.
      merged.select("rect.hit")
        .attr("tabindex", (p) => (p.opacity > OPACITY.hidden ? 0 : -1))
        .attr("aria-hidden", (p) => (p.opacity > OPACITY.hidden ? null : "true"))
        .style("pointer-events", (p) => (p.opacity > OPACITY.hidden ? null : "none"));
    }

    return { update: redrawable(svg, draw), svg };
  }

  /* Horizontal waterfall: each row is a bar from start to end.
     rows: [{key, label, start, end, kind: "up" | "down" | "total", opacity}] */
  function waterfall(elementId) {
    const svg = d3.select(`#${elementId}`).append("svg");
    const plot = svg.append("g");
    const xAxis = svg.append("g").attr("class", "x-axis");
    const zero = svg.append("line").attr("class", "zero-line");
    const xTitle = svg.append("text").attr("class", "axis-text").attr("text-anchor", "middle");
    const KIND_COLOR = { up: COLOR.accent, down: COLOR.series, total: COLOR.total };

    function draw(state) {
      const width = chartWidth(elementId);
      const narrow = width < SIZE.narrowAxis;
      const margin = {
        top: DOT_RANGE.marginTop,
        right: narrow ? DOT_RANGE.marginRightNarrow : DOT_RANGE.marginRight,
        bottom: DOT_RANGE.marginBottom,
        left: Math.min(WATERFALL.labelWidth, Math.round(width * DOT_RANGE.labelShare)),
      };
      const rows = state.rows;
      const plotBottom = margin.top + rows.length * WATERFALL.rowHeight;
      const height = plotBottom + margin.bottom;
      svg.attr("viewBox", `0 0 ${width} ${height}`);
      const x = d3.scaleLinear().domain(state.domain).range([margin.left, width - margin.right]);
      const y = d3.scaleBand().domain(rows.map((r) => r.key)).range([margin.top, plotBottom]);
      const barTop = (r) => y(r.key) + (y.bandwidth() - WATERFALL.barHeight) / 2;

      xAxis.attr("transform", `translate(0,${plotBottom})`)
        .transition().duration(MOTION.duration)
        .call(d3.axisBottom(x).ticks(narrow ? DOT_RANGE.ticksNarrow : DOT_RANGE.ticks).tickSize(-(plotBottom - margin.top)));
      xAxis.selectAll(".tick line").attr("class", "gridline");
      xTitle.attr("x", (margin.left + width - margin.right) / 2).attr("y", height - DOT_RANGE.titleOffset).text(state.xTitle);
      zero.attr("x1", x(0)).attr("x2", x(0)).attr("y1", margin.top).attr("y2", plotBottom);

      const labels = plot.selectAll("text.row-label").data(rows, (r) => r.key);
      labels.exit().remove();
      labels.enter().append("text").attr("class", "row-label").attr("text-anchor", "end")
        .merge(labels)
        .attr("x", margin.left - SIZE.rowLabelGap)
        .attr("y", (r) => y(r.key) + y.bandwidth() / 2)
        .classed("is-bold", (r) => r.kind === "total")
        .style("opacity", (r) => r.opacity)
        .text((r) => r.label)
        .call(wrapLabel, margin.left - SIZE.wrapGap);

      const bars = plot.selectAll("g.step-bar").data(rows, (r) => r.key);
      bars.exit().remove();
      const entered = bars.enter().append("g").attr("class", "step-bar");
      entered.append("rect").attr("rx", WATERFALL.radius).attr("height", WATERFALL.barHeight)
        .attr("x", x(0)).attr("width", 0);
      entered.append("text").attr("class", "value-label").attr("dy", "0.35em");
      const merged = entered.merge(bars);
      merged.select("rect")
        .attr("fill", (r) => KIND_COLOR[r.kind])
        .attr("y", barTop)
        .transition().duration(MOTION.duration)
        .attr("x", (r) => x(Math.min(r.start, r.end)))
        .attr("width", (r) => Math.max(1, Math.abs(x(r.end) - x(r.start))))
        .style("opacity", (r) => r.opacity);
      merged.select("text")
        .attr("y", (r) => y(r.key) + y.bandwidth() / 2)
        .text((r) => (r.kind === "total" ? fmt1(r.end - r.start) : signed(r.end - r.start, 2)))
        .transition().duration(MOTION.duration)
        .attr("x", (r) => x(Math.max(r.start, r.end)) + WATERFALL.labelGap)
        .style("opacity", (r) => r.opacity);
      attachTooltip(merged.select("rect"),
        (r) => `${r.kind === "total" ? fmt1(r.end - r.start) : signed(r.end - r.start, 2)} points`,
        (r) => r.label);

      const links = rows.slice(0, -1).map((r, i) => ({ key: r.key, x: r.end, from: r, to: rows[i + 1] }));
      const connectors = plot.selectAll("line.connector").data(links, (d) => d.key);
      connectors.exit().remove();
      connectors.enter().append("line").attr("class", "connector").merge(connectors)
        .style("opacity", (d) => Math.min(d.from.opacity, d.to.opacity) * OPACITY.context)
        .transition().duration(MOTION.duration)
        .attr("x1", (d) => x(d.x)).attr("x2", (d) => x(d.x))
        .attr("y1", (d) => barTop(d.from) + WATERFALL.barHeight)
        .attr("y2", (d) => barTop(d.to));
    }

    return { update: redrawable(svg, draw) };
  }

  // ================================================================ sections

  // ---- 1: 100 children
  (function () {
    const chart = unitGrids("units-chart");
    const title = byId("units-title");
    const controls = byId("units-controls");
    const view = { band: "0-5", showAll: false, highlight: false };

    legend("units-legend", [
      { label: "Mother rates her mental health fair or poor", color: COLOR.accent },
      { label: "Excellent, very good or good", color: COLOR.neutral },
    ]);
    table("units-table",
      [COLUMN.field("Child's age", "band"), COLUMN.field("Mother's employment", "group"),
        COLUMN.pct("Fair or poor (%)"), COLUMN.ci(), COLUMN.n("Mothers (n)")],
      DATA.fairPoorByBand);

    function render() {
      const names = view.showAll ? EMPLOYMENT : [EMPLOYMENT[0]];
      chart.update(names.map((name) => {
        const row = DATA.fairPoorByBand.find((r) => r.band === view.band && r.group === name);
        return {
          key: name,
          label: name,
          pct: view.highlight ? row.pct : 0,
          detail: `${childLabel(view.band)}. ${ciText(row.ci)}; ${fmtInt(row.n)} mothers surveyed.`,
        };
      }));
      title.textContent = view.showAll
        ? `Children ${BAND_TEXT[view.band]}, by what their mother does`
        : `100 children ${BAND_TEXT[view.band]} whose mothers work full-time`;
      for (const button of controls.querySelectorAll("button")) {
        button.setAttribute("aria-pressed", String(button.dataset.band === view.band));
      }
    }

    for (const band of BANDS) {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "pill";
      button.dataset.band = band;
      button.textContent = childLabel(band);
      button.addEventListener("click", () => {
        Object.assign(view, { band, showAll: true, highlight: true });
        render();
      });
      controls.appendChild(button);
    }

    const bandForStep = ["0-5", "0-5", "0-5", "6-11", "12-17"];
    onSteps("s-units", (step) => {
      Object.assign(view, { band: bandForStep[step], showAll: step >= 2, highlight: step >= 1 });
      render();
    });
  })();

  // ---- 2: gaps before and after adjustment
  (function () {
    const chart = dotRange("gaps-chart");
    const models = [
      { key: "M0", label: "Child's age and year only", color: COLOR.muted },
      { key: "M1", label: "+ income, education, marital status, children, age", color: COLOR.accent },
      { key: "M2", label: "+ physical health", color: COLOR.series },
    ];
    const modelOf = (key) => models.find((m) => m.key === key);
    const rows = EMPLOYMENT.slice(1).map((g) => ({ key: g, label: g }));

    legend("gaps-legend", models);
    table("gaps-table",
      [{ label: "Model", value: (r) => modelOf(r.model).label }, COLUMN.field("Group vs. full-time", "group"),
        { label: "Gap (points)", value: (r) => fmt1(r.gap) }, COLUMN.ci()],
      DATA.adjustedGaps);

    const modelsForStep = [["M0"], ["M0", "M1"], ["M0", "M1"], ["M0", "M1", "M2"], ["M0", "M1", "M2"]];
    const focusForStep = [null, "Looking for work", "Not looking for work", null, "Part-time"];

    onSteps("s-gaps", (step) => {
      const shown = modelsForStep[step];
      const focusGroup = focusForStep[step];
      const points = DATA.adjustedGaps.filter((r) => shown.includes(r.model)).map((r) => {
        const latest = r.model === shown[shown.length - 1];
        const inFocus = !focusGroup || r.group === focusGroup;
        return {
          row: r.group, series: r.model, value: r.gap, ci: r.ci, color: modelOf(r.model).color,
          opacity: inFocus ? (latest ? OPACITY.focus : OPACITY.context) : OPACITY.faded,
          label: latest && inFocus ? signed(r.gap) : "",
          tooltip: `${r.group} vs. full-time, ${modelOf(r.model).label}`,
        };
      });
      chart.update({ rows, points, domain: [-2, 10], seriesOrder: models.map((m) => m.key), signed: true,
        unit: " points", xTitle: "Percentage points higher than full-time mothers",
        xTitleShort: "Points above full-time mothers" });
    });
  })();

  // ---- 3a: gaps by child's age
  (function () {
    const chart = dotRange("age-chart", { labelWidth: 120 });
    const series = [
      { key: "Looking for work", label: "Looking for work", color: COLOR.series },
      { key: "Not looking for work", label: "Not looking for work", color: COLOR.accent },
    ];
    const colorOf = (key) => series.find((s) => s.key === key).color;
    const rows = BANDS.map((band) => ({ key: band, label: childLabel(band) }));
    const data = DATA.gapsByBand.filter((r) => r.group !== "Part-time");

    legend("age-legend", series);
    table("age-table",
      [COLUMN.field("Child's age", "band"), COLUMN.field("Group vs. full-time", "group"),
        { label: "Adjusted gap (points)", value: (r) => fmt1(r.gap) }, COLUMN.ci()],
      DATA.gapsByBand);

    onSteps("s-age", (step) => {
      const focus = step === 0 ? series[0].key : series[1].key;
      const points = data.map((r) => ({
        row: r.band, series: r.group, value: r.gap, ci: r.ci, color: colorOf(r.group),
        opacity: r.group === focus ? OPACITY.focus : OPACITY.faded,
        label: r.group === focus ? signed(r.gap) : "",
        tooltip: `${r.group} vs. full-time, ${childLabel(r.band).toLowerCase()}`,
      }));
      chart.update({ rows, points, domain: [-4, 10], seriesOrder: series.map((s) => s.key), signed: true,
        unit: " points", xTitle: "Adjusted percentage points higher than full-time mothers",
        xTitleShort: "Points above full-time mothers" });
    });
  })();

  // ---- 3b: building the gap, one factor at a time
  (function () {
    const chart = waterfall("split-chart");
    const title = byId("split-title");
    const subtitle = byId("split-subtitle");
    const decomposition = (group) => DATA.decomposition.find((d) => d.group === group);

    legend("split-legend", [
      { label: "Widens the gap", color: COLOR.accent, shape: "rect" },
      { label: "Narrows the gap", color: COLOR.series, shape: "rect" },
      { label: "Total", color: COLOR.total, shape: "rect" },
    ]);

    const tableRows = [];
    for (const d of DATA.decomposition) {
      for (const c of d.contributions) {
        tableRows.push({ group: d.group, name: c.name, pts: c.pts });
      }
      tableRows.push({ group: d.group, name: "Explained (total)", pts: d.explained });
      tableRows.push({ group: d.group, name: "Unexplained", pts: d.unexplained });
    }
    table("split-table",
      [{ label: "Gap", value: (r) => `${r.group} vs. full-time` }, COLUMN.field("Part", "name"),
        { label: "Points", value: (r) => fmt1(r.pts) }],
      tableRows);

    // Rows: each factor from the running total, then explained, unexplained and the whole gap.
    function rowsFor(d, show) {
      const factors = d.contributions.filter((c) => Math.abs(c.pts) >= 0.005).sort((a, b) => b.pts - a.pts);
      let running = 0;
      const rows = factors.map((c) => {
        const row = { key: c.name, label: c.name, start: running, end: running + c.pts,
          kind: c.pts > 0 ? "up" : "down", opacity: show.factors };
        running += c.pts;
        return row;
      });
      rows.push({ key: "explained", label: "Explained by these factors", start: 0, end: d.explained,
        kind: "total", opacity: show.explained });
      rows.push({ key: "unexplained", label: "Not explained", start: d.explained, end: d.raw,
        kind: "up", opacity: show.unexplained });
      rows.push({ key: "gap", label: `Gap: ${d.group.toLowerCase()} vs. full-time`, start: 0, end: d.raw,
        kind: "total", opacity: show.unexplained });
      return rows;
    }

    const views = [
      { group: "Looking for work", show: { factors: OPACITY.focus, explained: OPACITY.faded, unexplained: OPACITY.faded } },
      { group: "Looking for work", show: { factors: OPACITY.focus, explained: OPACITY.focus, unexplained: OPACITY.faded } },
      { group: "Looking for work", show: { factors: OPACITY.context, explained: OPACITY.context, unexplained: OPACITY.focus } },
      { group: "Not looking for work", show: { factors: OPACITY.focus, explained: OPACITY.focus, unexplained: OPACITY.focus } },
    ];

    onSteps("s-split", (step) => {
      const view = views[step];
      const d = decomposition(view.group);
      title.textContent = `Building the ${fmt1(d.raw)}-point gap: ${d.group.toLowerCase()} vs. full-time mothers`;
      subtitle.textContent = "Fair or poor mental health, percentage points, one factor at a time";
      chart.update({ rows: rowsFor(d, view.show), domain: [-1.5, 7.5], xTitle: "Percentage points" });
    });
  })();

  // ---- 3c: inside the model (odds ratios)
  (function () {
    const chart = dotRange("model-chart", {
      labelWidth: FOREST.labelWidth, rowHeight: FOREST.rowHeight, rowHeightNarrow: FOREST.rowHeightNarrow, fitScreen: true,
    });
    const SHOWN = {
      EMP: "Work (vs. full-time)",
      INCOME: "Income (vs. 400%+ FPL)",
      EDUCATION: "Education (vs. bachelor's)",
      MARITAL: "Marital (vs. married)",
      AGE: "Mother's age (vs. 35-44)",
    };
    const SHOWN_NARROW = { EMP: "Work", INCOME: "Income", EDUCATION: "Education", MARITAL: "Marital", AGE: "Mother's age" };
    const SHORT_LEVEL = {
      "Some college, vocational or associate": "Some college",
      "Divorced, separated or widowed": "Formerly married",
      "Living with a partner": "Partnered",
    };
    const NARROW_LEVEL = { "Looking for work": "Looking", "Not looking for work": "Not looking" };
    const focusForStep = [["EMP"], ["INCOME"], ["MARITAL"], ["EDUCATION", "AGE"]];
    const terms = DATA.oddsRatios.filter((r) => SHOWN[r.variable]);
    const rows = [];
    for (const variable of Object.keys(SHOWN)) {
      rows.push({ key: variable, label: SHOWN[variable], labelNarrow: SHOWN_NARROW[variable], bold: true });
      for (const r of terms.filter((t) => t.variable === variable)) {
        rows.push({ key: `${variable}|${r.level}`, label: SHORT_LEVEL[r.level] || r.level, labelNarrow: NARROW_LEVEL[r.level] });
      }
    }

    legend("model-legend", [
      { label: "Higher odds than the comparison group", color: COLOR.accent },
      { label: "Lower odds", color: COLOR.series },
      { label: "Not distinguishable (CI crosses 1)", color: COLOR.muted },
    ]);
    table("model-table",
      [COLUMN.field("Variable", "variable"), COLUMN.field("Group", "level"),
        { label: "Odds ratio", value: (r) => r.or.toFixed(2) }, COLUMN.ci(), { label: "p", value: (r) => r.p.toFixed(3) }],
      DATA.oddsRatios);

    const colorOf = (r) => (r.ci[0] > 1 ? COLOR.accent : r.ci[1] < 1 ? COLOR.series : COLOR.muted);

    onSteps("s-model", (step) => {
      const focus = focusForStep[step];
      chart.update({
        rows,
        points: terms.map((r) => {
          const inFocus = focus.includes(r.variable);
          return {
            row: `${r.variable}|${r.level}`, series: "or", value: r.or, ci: r.ci, color: colorOf(r),
            opacity: inFocus ? OPACITY.focus : OPACITY.faded,
            label: inFocus ? r.or.toFixed(2) : "",
            tooltip: `${SHOWN[r.variable]}: ${r.level}`,
          };
        }),
        log: true, reference: 1, domain: FOREST.domain, tickValues: FOREST.ticks,
        tickFormat: (v) => `${v}`, xTitle: "Odds ratio (log scale)",
      });
    });
  })();

  // ---- 4: mothers of children under 2
  (function () {
    const chart = dotRange("baby-chart");
    const title = byId("baby-title");
    const subtitle = byId("baby-subtitle");
    const JOB_CHANGE = "Family job change because of child care";
    const views = [
      { outcome: "Fair or poor mental health", comparison: "employment", domain: [0, 20],
        title: "Mothers of children under 2: fair or poor mental health" },
      { outcome: "Good, fair or poor mental health", comparison: "employment", domain: [0, 60],
        title: "Mothers of children under 2: mental health below \"very good\"" },
      { outcome: "Good, fair or poor mental health", comparison: "child age", domain: [0, 60],
        title: "Full-time mothers, by child's age: mental health below \"very good\"" },
      { outcome: "Frequent parenting aggravation", comparison: "child age", domain: [0, 10],
        title: "Full-time mothers, by child's age: frequent parenting aggravation" },
    ];
    const highlightFor = { employment: "Full-time", "child age": "Under 2" };
    const groupLabel = (r) => {
      const name = r.comparison === "child age" ? childLabel(r.group === "Under 2" ? "under 2" : r.group) : r.group;
      return r.flag ? `${name} †` : name;
    };

    subtitle.textContent = "Adjusted percentage with 95% confidence interval";
    legend("baby-legend", [
      { label: "Highlighted group", color: COLOR.accent },
      { label: "Comparison groups", color: COLOR.muted },
    ]);
    table("baby-table",
      [COLUMN.field("Outcome", "outcome"),
        { label: "Comparison", value: (r) => (r.comparison === "employment" ? "Mothers of children under 2, by employment" : "Full-time mothers, by child's age") },
        COLUMN.field("Group", "group"), COLUMN.pct("Adjusted %"), COLUMN.ci(),
        { label: "Reliability", value: (r) => (r.flag ? "flagged" : "") }],
      DATA.under2.filter((r) => r.outcome !== JOB_CHANGE));

    onSteps("s-baby", (step) => {
      const view = views[step];
      const highlight = highlightFor[view.comparison];
      const data = DATA.under2.filter((r) => r.outcome === view.outcome && r.comparison === view.comparison);
      title.textContent = view.title;
      chart.update({
        rows: data.map((r) => ({ key: r.group, label: groupLabel(r), bold: r.group === highlight })),
        points: data.map((r) => ({
          row: r.group, series: view.outcome, value: r.pct, ci: r.ci,
          color: r.group === highlight ? COLOR.accent : COLOR.muted,
          opacity: OPACITY.focus, label: `${fmt1(r.pct)}%`,
          tooltip: r.flag ? `${r.group} (flagged as unreliable)` : r.group,
        })),
        domain: view.domain, unit: "%", xTitle: "Adjusted percentage", tickFormat: (v) => `${v}%`,
      });
    });
  })();

  // ---- 5: child care job changes
  (function () {
    const chart = unitGrids("care-chart");
    const title = byId("care-title");
    const data = DATA.under2.filter((r) => r.outcome === "Family job change because of child care" && r.comparison === "employment");

    legend("care-legend", [
      { label: "Someone in the family quit, turned down or changed a job because of child care", color: COLOR.accent },
      { label: "No such job change", color: COLOR.neutral },
    ]);
    table("care-table",
      [COLUMN.field("Mother's employment", "group"), COLUMN.pct("Adjusted %"), COLUMN.ci(), COLUMN.n("Mothers (n)")],
      data);

    onSteps("s-care", (step) => {
      const names = step === 0 ? [EMPLOYMENT[0]] : EMPLOYMENT;
      chart.update(names.map((name) => {
        const row = data.find((r) => r.group === name);
        return { key: name, label: name, pct: row.pct, detail: `${ciText(row.ci)}; ${fmtInt(row.n)} mothers of children under 2.` };
      }));
      title.textContent = step === 0
        ? "100 families with a child under 2 and a mother working full-time"
        : "100 families with a child under 2, by what the mother does";
    });
  })();

  // ---- 6: mothers and fathers
  (function () {
    const chart = dotRange("dads-chart", { labelWidth: 170, rowHeight: 40 });
    const series = [
      { key: "Full-time", label: "Full-time", color: COLOR.muted },
      { key: "Not employed", label: "Not employed", color: COLOR.accent },
    ];
    const colorOf = (key) => series.find((s) => s.key === key).color;
    const parentName = { mothers: "Mothers", fathers: "Fathers" };
    const levels = DATA.fathers.levels.filter((r) => r.group !== "Part-time");
    const rows = [];
    for (const parent of Object.keys(parentName)) {
      for (const band of BANDS) {
        rows.push({
          key: `${parent}|${band}`,
          label: `${parentName[parent]}, ${childLabel(band).toLowerCase()}`,
          labelNarrow: `${parentName[parent]}, ${band.replace("-", "–")}`,
        });
      }
    }

    legend("dads-legend", series);
    table("dads-table",
      [COLUMN.field("Parent", "parent"), COLUMN.field("Child's age", "band"), COLUMN.field("Employment", "group"),
        COLUMN.pct("Fair or poor (%)"), COLUMN.ci(), COLUMN.n()],
      DATA.fathers.levels);

    onSteps("s-dads", (step) => {
      chart.update({
        rows,
        points: levels.map((r) => {
          const visible = step > 0 || r.parent === "mothers";
          const focus = step !== 1 || r.parent === "fathers";
          return {
            row: `${r.parent}|${r.band}`, series: r.group, value: r.pct, ci: r.ci, color: colorOf(r.group),
            opacity: visible ? (focus ? OPACITY.focus : OPACITY.context) : OPACITY.hidden,
            label: r.group === "Not employed" && visible && focus ? `${fmt1(r.pct)}%` : "",
            tooltip: `${parentName[r.parent]}, ${r.group.toLowerCase()}, ${childLabel(r.band).toLowerCase()}`,
          };
        }),
        domain: [0, 16], connect: true, seriesOrder: series.map((s) => s.key), unit: "%",
        xTitle: "Percentage of children whose parent reports fair or poor mental health",
        xTitleShort: "% with fair or poor mental health",
        tickFormat: (v) => `${v}%`,
      });
    });
  })();

  initThemeToggle("theme-toggle");
})();
